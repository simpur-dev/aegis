# ============================================================
# 解释节点：用户提示词构造函数
# ============================================================


def build_explain_user_prompt(alert_json: str, required_keyword: str = "", retry_count: int = 0, previous_issues: str = "") -> str:
    """构造解释节点的用户提示词。

    参数:
        alert_json: 结构化预警对象 JSON
        required_keyword: 说明文本中必须出现的等级关键词（如"提示"）
    """
    base = (
        f"=== 结构化预警对象（唯一事实来源，数字与时间逐字引用）===\n{alert_json}\n\n"
        f"=== 硬性要求 ===\n"
        f"说明文本（summary 或 bullet_points）中必须出现关键词「{required_keyword}」。\n\n"
        f"请将其转化为可读的预警说明。"
    )
    if retry_count > 0 and previous_issues:
        base += (
            f"\n\n注意：这是第 {retry_count} 次生成说明。"
            f"\n上次校验发现的问题：{previous_issues}"
            f"\n请针对性修正（仍不得改变等级或编造内容）。"
        )
    return base
